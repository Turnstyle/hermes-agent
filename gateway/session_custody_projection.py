def _unknown(status):
    return {
        'version': 1, 'status': status,
        'resource_root': RESOURCE_ROOT, 'maker_profile': MAKER_PROFILE,
        'maker_config': MAKER_CONFIG, 'readiness': 'UNPROVEN',
        'rows': [{
            'provider': p, 'field': 'api_key',
            'maker_launch_available': None,
            'reconstructed_scope_available': None,
            'prospective_inherited_clean_child_available': None,
            'standalone_relaunch_available': None,
            'actual_child_authentication': 'NOT RUN',
        } for p in PROVIDERS],
    }


def _valid_names(names):
    import re
    return (type(names) is dict and set(names) == set(PROVIDERS)
            and all(type(n) is str and re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', n)
                    for n in names.values()))


def _valid_context(lease, current):
    admitted = lease.admitted
    if type(current) is not dict or type(admitted) is not dict:
        return False
    required = {'actor_home': ACTOR_HOME, 'task_id': CUSTODY_TASK, 'board': BOARD,
                'resource_root': RESOURCE_ROOT, 'source': 'kanban', 'dispatcher_owned': True}
    if any(current.get(k) != v for k, v in required.items()):
        return False
    if current.get('dispatcher_owned') is not True:
        return False
    tenant = lease.authorized_tenant
    if type(tenant) is not str or not tenant or current.get('tenant') != tenant:
        return False
    if any(type(current.get(k)) is not str or not current[k]
           for k in ('session_id', 'execution_id')):
        return False
    if type(current.get('epoch')) is not int or current['epoch'] < 1:
        return False
    keys = (*required, 'tenant', 'session_id', 'execution_id', 'epoch')
    return all(current.get(k) == admitted.get(k) for k in keys)


def _project_witnesses(row, witnesses):
    # This projection authenticates nothing: provenance must be generated by the
    # native owner. It rejects malformed/ambiguous results rather than guessing.
    keys = {'kind', 'available', 'resource_root', 'maker_home', 'maker_config',
            'launch_capture_id', 'executed', 'reference_only'}
    kinds = {'actual_maker_launch': 'maker_launch_available',
             'reconstructed_owner_scope': 'reconstructed_scope_available',
             'prospective_reference_child': 'prospective_inherited_clean_child_available'}
    if type(witnesses) not in (tuple, list) or len(witnesses) > 3:
        return
    valid = {}
    for w in witnesses:
        if (type(w) is not dict or set(w) != keys or type(w.get('kind')) is not str
                or w['kind'] not in kinds or w['kind'] in valid):
            return
        if (w['resource_root'] != RESOURCE_ROOT or w['maker_home'] != MAKER_HOME
                or w['maker_config'] != MAKER_CONFIG
                or (w['available'] is not None and type(w['available']) is not bool)
                or type(w['executed']) is not bool or type(w['reference_only']) is not bool
                or type(w['launch_capture_id']) is not str):
            return
        valid[w['kind']] = w
    for kind, w in valid.items():
        if kind == 'actual_maker_launch' and not (w['executed'] and w['launch_capture_id']):
            continue
        if kind == 'prospective_reference_child':
            launch = valid.get('actual_maker_launch')
            if not (w['executed'] and w['reference_only'] and launch
                    and launch['executed'] and w['launch_capture_id']
                    and w['launch_capture_id'] == launch['launch_capture_id']):
                continue
        row[kinds[kind]] = w['available']


def observe(approved_names, *, native=None):
    """Fixed in-process contract; native is owner-injected, never deserialized.

    Names are private in-memory custody input. No exception text is caught,
    transformed or retried: the native handler must preserve its real denial.
    """
    if native is None:
        return _unknown('native_observer_unavailable')
    if not _valid_names(approved_names):
        return _unknown('invalid_approved_names')
    with native.lease() as lease:
        before = lease.current_context()
        if not _valid_context(lease, before):
            return _unknown('native_context_denied')
        lease.revalidate()
        result = _unknown('projected_witnesses')
        for row in result['rows']:
            witnesses = lease.observe_reference(row['provider'], approved_names[row['provider']])
            _project_witnesses(row, witnesses)
        lease.revalidate()
        after = lease.current_context()
        if not _valid_context(lease, after) or after != before:
            return _unknown('native_context_denied')
        return result
